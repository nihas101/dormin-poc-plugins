local function decode_player_name(player_name)
    local n = {}
    for i = 1, #player_name do
        local b = player_name[i]
        n[#n + 1] = char_set[b] or "?"
    end
    return table.concat(n):gsub("%s+$", "") -- trim trailing blanks
end

function handle_event(msg)
    print("HandleEvent called with " .. msg.type)

    if msg.type == "text_displayed" then
        local line = sfc_lines[msg.text_id]
        if line ~= nil then
            print(decode_player_name(msg.player_name)) -- TODO: Substitute for the placeholder in the script
            callJSFunction("displayScript", line)
        else
            print("Unknown msg.text_id: " .. tostring(msg.text_id))
        end
    elseif msg.type == "text_closed" then
        callJSFunction("clearAllData")
    else
        print("Unknown msg.type: " .. tostring(msg.type))
    end
end
